    public void botonPulsado (JButton boton){
        if (turno) {
            boton.setText("X");
            turnoLabel.setText("Turno del jugador O");
            turno = false;
        } else {
            boton.setText("O");
            turnoLabel.setText("Turno del jugador X");
            turno = true;
        }
        
        boton.setEnabled(false);
    
    }
    
    
    
