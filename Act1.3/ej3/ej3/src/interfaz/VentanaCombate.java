    private void especialButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_especialButtonActionPerformed
        //Activa la habilidad especial segun la clase del personaje
        switch (pj.getClass().getSimpleName()) {
            case "Barbaro":
                ((Barbaro) pj).activarFuria();
                textArea.append(linea + pj.getNombre() + " activa su FURIA");
                break;
            case "Picaro": {
                ((Picaro) pj).usarCapaYEspada();
                textArea.append(linea + pj.getNombre() + " usa CAPA Y ESPADA: esquivara el proximo golpe y su siguiente ataque sera critico");
                break;
            }
            case "Clerigo": {
                int curado = ((Clerigo) pj).novaCurativa();
                textArea.append(linea + pj.getNombre() + " lanza NOVA CURATIVA y recupera " + curado + " puntos de vida");
                break;
            }
            default:

        }
        //Usar la habilidad gasta el turno: el jefe responde
        pjStarter(pj);
        turnoDelJefe();
    }//GEN-LAST:event_especialButtonActionPerformed

    private String getImageName(Personaje pj){
        String imageName="";
        
        switch (pj.getClass().getSimpleName()) {
            case "Barbaro":
                imageName="barbarian.png";
                
                break;
            case "Picaro":
                imageName="rogue.png";
                
                break;
            case "Clerigo":
                imageName="cleric.png";
                break;
            default:
                
        }
    
        return imageName;
    }
       //Ocupa URL para obtener el archivo. Comprueba el null, y despues pasando la url a un ImageIcon que permite convertirlo en un Image.
    //con 146 pongo los limites de la imagen de ancho y con -1 permite que la altura se ajuste a necesidad de la imagen. Con SCALE_SMOOTH 
    //Prioriza la imagen sobre los recursos usado para imprimir.
    //Finalmente convierte la Image en ImageIcon y se lo pasa a un JLabel
    public void mostrarImagen(String archivo, JLabel imgLabel) {
        java.net.URL url = getClass().getResource("/imagenes/" + archivo);
        if (url == null) {
            imgLabel.setIcon(null);
            System.out.println("No se encuentra la imagen: " + archivo);
            return;
        }
        java.awt.Image img = new ImageIcon(url).getImage()
                .getScaledInstance(146, -1, java.awt.Image.SCALE_SMOOTH);
        imgLabel.setIcon(new ImageIcon(img));
    }
    //El jefe responde y se cierra la ronda
    private void turnoDelJefe() {
        pausa(1000);
        textArea.append("\n" + boss.ataca(pj) + linea);
        cierraTurno();
    }

    //Final de ronda: avisa al personaje (duracion y enfriamiento de habilidades), refresca y comprueba el final
    private void cierraTurno() {
        pj.finDeTurno();
        pjStarter(pj);
        bossStarter();
        comprobarFinal();
        actualizaBotonEspecial();
    }
    //Comprueba muertos y reinicia el juego si es que se murio alguien
    private void comprobarFinal() {
        boolean terminado = true;

        if (!pj.vivo() && !boss.vivo()) {
            textArea.append(linea + "EMPATE" + linea);
        } else if (!pj.vivo()) {
            textArea.append(linea + boss.getNombre() + " GANA" + linea);
        } else if (!boss.vivo()) {
            textArea.append(linea + pj.getNombre() + " GANA" + linea);
        } else {
            terminado = false;
        }

        if (terminado) {
            atacarButton.setEnabled(false);
            especialButton.setEnabled(false);
            Timer t = new Timer(5000, e -> {
                new VentanaSeleccion().setVisible(true);
                dispose();
            });
            t.setRepeats(false);
            t.start();
        }
    }

    //El boton especial solo esta activo si la habilidad se puede usar y el combate sigue
    private void actualizaBotonEspecial() {
        boolean disponible = false;
        if (pj.vivo() && boss.vivo()) {
            switch (pj.getClass().getSimpleName()) {
                case "Barbaro":
                    disponible = ((Barbaro) pj).puedeUsarFuria();
                    break;
                case "Picaro":
                    disponible = ((Picaro) pj).puedeUsarCapaYEspada();
                    break;
                case "Clerigo":
                    disponible = ((Clerigo) pj).puedeUsarNova();
                    break;
                default:
            }
        }
        especialButton.setEnabled(disponible);
    }

    //Pausa de 1 segundo entre el ataque del jugador y la respuesta del jefe
    private void pausa(long millis) {
        try {
            Thread.sleep(millis);
        } catch (InterruptedException ex) {
            System.getLogger(VentanaCombate.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            Thread.currentThread().interrupt();
        }
    }

    /*Revisa la clase del pj y pone el nombre de la habilidad en el boton*/
    private void nombreBotonSetter(Personaje pj) {

        switch (pj.getClass().getSimpleName()) {
            case "Barbaro":
                especialButton.setText("FURIA");
                break;
            case "Picaro":
                especialButton.setText("CAPA Y ESPADA");
                break;
            case "Clerigo":
                especialButton.setText("NOVA CURATIVA");
                break;
            default:
                especialButton.setText(" ");
        }
    }

