    private void selectClaseComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_selectClaseComboBoxActionPerformed
        String clase = (String) selectClaseComboBox.getSelectedItem();

        switch (clase) {
            case "Barbaro":
                descripcionTextPanel.setText(new Barbaro().getDescripcion());
                mostrarImagen("barbarian.png");
                break;
            case "Picaro":
                descripcionTextPanel.setText(new Picaro().getDescripcion());
                mostrarImagen("rogue.png");
                break;
            case "Clerigo":
                descripcionTextPanel.setText(new Clerigo().getDescripcion());
                mostrarImagen("cleric.png");
                break;
            default:
                descripcionTextPanel.setText("Seleccione una clase ");
                imgLabel.setIcon(null);
        }
    }//GEN-LAST:event_selectClaseComboBoxActionPerformed

