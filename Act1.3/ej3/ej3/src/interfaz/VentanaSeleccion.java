    private void pelearBotonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pelearBotonActionPerformed
        String clase = (String) selectClaseComboBox.getSelectedItem();
        String nombre = nombreTextField.getText();

        if (clase.isBlank()) {
            new Aviso(VentanaSeleccion.this, true, "ELIGE UNA CLASE").setVisible(true);
        } else if (nombre.isBlank()) {
            new Aviso(VentanaSeleccion.this, true, "ELIGE UN NOMBRE DE PERSONAJE").setVisible(true);

        } else {
            switch (clase) {
                case "Barbaro":
                    Barbaro barbaro = new Barbaro(nombre);
                    System.out.println(barbaro.toString()); //DEBUG LINE
                    new VentanaCombate(barbaro).setVisible(true);
                    VentanaSeleccion.this.dispose();
                    break;

                case "Picaro":
                    Picaro picaro = new Picaro(nombre);
                    System.out.println(picaro.toString()); //DEBUG LINE
                    new VentanaCombate(picaro).setVisible(true);
                    VentanaSeleccion.this.dispose();
                    break;
                case "Clerigo":
                    Clerigo clerigo = new Clerigo(nombre);
                    System.out.println(clerigo.toString()); //DEBUG LINE
                    new VentanaCombate(clerigo).setVisible(true);
                    VentanaSeleccion.this.dispose();
                    break;
                default:

            }
        }
    }//GEN-LAST:event_pelearBotonActionPerformed
    //Ocupa URL para obtener el archivo. Comprueba el null, y despues pasando la url a un ImageIcon que permite convertirlo en un Image.
    //con 146 pongo los limites de la imagen de ancho y con -1 permite que la altura se ajuste a necesidad de la imagen. Con SCALE_SMOOTH 
    //Prioriza la imagen sobre los recursos usado para imprimir.
    //Finalmente convierte la Image en ImageIcon y se lo pasa a un JLabel
    public void mostrarImagen(String archivo) {
        java.net.URL url = getClass().getResource("/imagenes/" + archivo);
        if (url == null) {
            imgLabel.setIcon(null);
            System.out.println("No se encuentra la imagen: " + archivo);
            return;
        }
        java.awt.Image img = new ImageIcon(url).getImage()
                .getScaledInstance(146, -1, java.awt.Image.SCALE_SMOOTH);
        imgLabel.setIcon(new ImageIcon(img));
    }

