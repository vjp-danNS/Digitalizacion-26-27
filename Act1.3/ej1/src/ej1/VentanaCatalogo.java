    private void registrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrarButtonActionPerformed
        // TODO add your handling code here:
        String titulo;
        int numPag = -1;
        boolean alamacenado;
        
        titulo= tituloTextField.getText();
        try {
            numPag= Integer.parseInt(pagTextField.getText());
        } catch (NumberFormatException e) {
            e.printStackTrace();
        }
        
        alamacenado= almacenadoCheckBox.isSelected();
        if (numPag<=0) {
            registroTextArea.append("\n--------------------"
                    + "\nFALTA EL NUMERO DE PAGINAS"
                    + "\n--------------------");
        }else{
            Libro l = new Libro(numPag, titulo, alamacenado);
            catalogo.add(l);
            
            Iterator<Libro> it= catalogo.iterator();
            
            registroTextArea.append("\n--------------------"
                        + "\nCATALOGO"
                        + "\n--------------------");
            
            for (Iterator<Libro> iterator = catalogo.iterator(); iterator.hasNext();) {
                Libro next = iterator.next();
                registroTextArea.append("\n"+next.toString()
                        + "\n--------------------");
            }
        }
        
        
        
    }//GEN-LAST:event_registrarButtonActionPerformed

