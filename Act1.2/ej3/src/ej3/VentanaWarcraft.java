    private void atacarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atacarButtonActionPerformed
        textArea.append("\n> " + p1.ataca(p2));
        vidaLabel2.setText("Vida: " + Integer.toString(p2.getVida()));

        if (!p2.vivo()) {
            textArea.append("\n> " + p1.getNombre() + " HA GANADO");
            atacarButton.setEnabled(false);
            atacarButton2.setEnabled(false);

            nombreTextField1.setEnabled(true);
            nombreTextField2.setEnabled(true);

            startButton.setEnabled(true);

            textArea.append("\n\n\n> Introduce ambos nombres para empezar");
        }
    }//GEN-LAST:event_atacarButtonActionPerformed

