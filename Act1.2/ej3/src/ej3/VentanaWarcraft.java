    private void startButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_startButtonActionPerformed
        if (!(nombreTextField1.getText().isBlank()) && !(nombreTextField2.getText().isBlank())) {
            atacarButton.setEnabled(true);
            atacarButton2.setEnabled(true);

            p1 = new Personaje(nombreTextField1.getText());
            p2 = new Personaje(nombreTextField2.getText());

            vidaLabel1.setText("Vida: " + Integer.toString(p1.getVida()));
            vidaLabel2.setText("Vida: " + Integer.toString(p2.getVida()));

            fueraLabel1.setText("Fuerza: " + Integer.toString(p1.getFuerza()));
            fuerzaLabel2.setText("Fuerza: " + Integer.toString(p2.getFuerza()));

            defensaLabel1.setText("Defensa: " + Integer.toString(p1.getDefensa()));
            defensaLabel2.setText("Defensa: " + Integer.toString(p2.getDefensa()));

            textArea.append("\n> Player 1 = " + nombreTextField1.getText() + " Player 2 = " + nombreTextField2.getText() + "\n> PELEEN"
                    + "\n\n>---------------------------------------------------------------------------------");
            nombreTextField1.setEnabled(false);
            nombreTextField2.setEnabled(false);

            startButton.setEnabled(false);

        } else {
            textArea.append("\n> Nombres todavia no agregados");

        }
    }//GEN-LAST:event_startButtonActionPerformed

