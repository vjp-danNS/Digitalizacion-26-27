    private void sumarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sumarButtonActionPerformed
        try {
            int n1 = Integer.parseInt(numTextField1.getText());
            int n2 = Integer.parseInt(numTextField2.getText());

            SumadorPares sum = new SumadorPares(n1, n2);
            int suma = sum.sumar();
            resultadoLabel.setText(String.valueOf(suma));
        } catch (NumberFormatException e) {
            resultadoLabel.setText("Caracter no valido");
        }
    }//GEN-LAST:event_sumarButtonActionPerformed

