    private void registrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrarButtonActionPerformed

     

        boolean almacenado = false;
        String nombre = nombreTextField.getText();
        int numPag = -1;

        try {
            numPag = Integer.parseInt(numPagTextField.getText());
            
        } catch (NumberFormatException e) {

            System.out.println("ERROR ");

        }

        if (almacenadoCheckBox.isSelected()) {
            almacenado = true;
        }

        Libro libro = new Libro(numPag, nombre, almacenado);
        System.out.println(libro.toString());
        if (numPag==-1) {
            infoLabel.setText("Faltan la cantidad de hojas");
        } else {
            infoLabel.setText(libro.toString());
        }
        

    }//GEN-LAST:event_registrarButtonActionPerformed

